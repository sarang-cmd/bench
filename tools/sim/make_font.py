#!/usr/bin/env python3
"""Generate tools/sim/sim_font.h, the 6x10 bitmap font the host preview uses.

The calculator draws text with gint's own font; this table only exists so the
screens can be rendered to PNG on a PC.  Requires Pillow and a DejaVu font
(any Linux install has one; `pip install pillow` otherwise).

    python3 tools/sim/make_font.py
"""

import sys

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 6, 10
OFFSET_Y = -2
SIZE = 10
FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/TTF/DejaVuSansMono.ttf",
]


def main() -> int:
    path = FONT_CANDIDATES[0]
    try:
        font = ImageFont.truetype(path, SIZE)
    except OSError:
        print(f"missing font: {path}", file=sys.stderr)
        return 1

    lines = [
        "/* sim_font.h - 6x10 bitmap font for the host preview only.",
        " *",
        " * Generated by tools/sim/make_font.py from DejaVu Sans Mono 10px.",
        " * The calculator uses gint's own font; this table exists so the",
        " * preview screenshots can be drawn on a PC without gint.",
        " * One unsigned short per column, bit 0 = top row, ten rows used. */",
        "",
        "#ifndef BENCH_SIM_FONT_H",
        "#define BENCH_SIM_FONT_H",
        "",
        f"#define SIM_FONT_W {WIDTH}",
        f"#define SIM_FONT_H {HEIGHT}",
        "#define SIM_FONT_FIRST 32",
        "#define SIM_FONT_LAST 126",
        "",
        "static const unsigned short sim_font[SIM_FONT_LAST - SIM_FONT_FIRST + 1]"
        "[SIM_FONT_W] = {",
    ]

    for cp in range(32, 127):
        image = Image.new("1", (WIDTH, HEIGHT), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0, OFFSET_Y), chr(cp), font=font, fill=1)
        columns = []
        for x in range(WIDTH):
            bits = 0
            for y in range(HEIGHT):
                if image.getpixel((x, y)):
                    bits |= 1 << y
            columns.append(bits)
        cells = ", ".join(f"0x{c:03x}" for c in columns)
        lines.append(f"    {{ {cells} }}, /* '{chr(cp)}' */")

    lines += ["};", "", "#endif"]
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
