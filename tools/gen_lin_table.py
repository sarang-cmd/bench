#!/usr/bin/env python3
"""Writes src/core/lin_table.h: the sRGB linearisation curve, as a table.

The contrast check needs the WCAG relative luminance, which is

    lin(c) = c/12.92                     when c/255 <= 0.03928
    lin(c) = ((c/255 + 0.055) / 1.055)^2.4   otherwise

and the 2.4 power needs libm.  src/core must stay libm-free (the real build
links fxlibc, which has no pow), so the curve is baked into a constant table of
256 uint16 values, scaled by 65535.  This script regenerates it; the numbers in
the header are the output, not hand-written.

    python3 tools/gen_lin_table.py > src/core/lin_table.h
"""

TABLE = []
for c in range(256):
    x = c / 255.0
    lin = x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    TABLE.append(round(lin * 65535))

print("/* lin_table.h - sRGB linearisation, generated by tools/gen_lin_table.py.")
print(" * Do not edit: run the script.  Value = linear light * 65535 for the")
print(" * 8-bit channel value at that index. */")
print()
print("#ifndef BENCH_LIN_TABLE_H")
print("#define BENCH_LIN_TABLE_H")
print()
print("#include <stdint.h>")
print()
print("static uint16_t const lin_lut[256] = {")
for row in range(0, 256, 8):
    cells = ", ".join(f"{v:5d}" for v in TABLE[row : row + 8])
    print(f"    {cells},")
print("};")
print()
print("#endif /* BENCH_LIN_TABLE_H */")
