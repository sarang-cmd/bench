#!/usr/bin/env python3
"""Writes spike/spike.diff: the spike add-in as a patch that can be applied.

The spike (`spike/`) answers ten questions about the real calculator - file
APIs and paths, float printing, font coverage, key values, tick rate, heap,
drawable area, redraw cost, empty-add-in size.  It is not part of Bench and it
is not on any release (see docs/spike.md).

Keeping a `.diff` next to the sources means the spike can be carried into a
checkout, a toolchain container or a support thread as one file, without
dragging the rest of the repository along:

    git apply spike/spike.diff            # from the repository root

The patch is generated, not written by hand, so it cannot drift from the
sources:

    make spike-patch

CI regenerates it and fails when the committed copy differs.
"""

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = ["spike/CMakeLists.txt", "spike/main.c"]
TARGET = ROOT / "spike" / "spike.diff"

HEADER = """\
# The M1 spike add-in, as a patch.
#
# This is a diagnostic add-in, not Bench: it measures ten things on the real
# calculator and prints the answers.  It is deliberately not released and not
# part of the .g3a (docs/spike.md says why).
#
# Apply it from the repository root, on a checkout that does not already have
# the files (git will refuse to overwrite them):
#
#     git apply spike/spike.diff
#     cd spike && fxsdk build-cg
#
# Generated by tools/gen_spike_patch.py; do not edit by hand.

"""


def main() -> int:
    parts = []
    for rel in FILES:
        out = subprocess.run(
            ["git", "diff", "--no-index", "--", "/dev/null", rel],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        # git diff --no-index exits 1 when there is a difference, which is
        # exactly what we want here.
        if out.returncode not in (0, 1) or not out.stdout:
            print(f"cannot diff {rel}: {out.stderr.strip()}", file=sys.stderr)
            return 1
        parts.append(out.stdout)

    text = HEADER + "".join(parts)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
